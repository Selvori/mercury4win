use super::*;
use crate::db::agent_result_store::{AgentResult, ResultSlot};

async fn pool() -> Pool {
    let pool = deadpool_sqlite::Config::new(":memory:")
        .builder(deadpool_sqlite::Runtime::Tokio1)
        .unwrap()
        .max_size(1)
        .build()
        .unwrap();
    pool.get().await.unwrap().interact(|conn| {
        crate::db::migrations::run_migrations(conn).unwrap();
        conn.execute_batch("INSERT INTO feed(id,title,feed_url) VALUES(1,'订阅作者','https://fixture.test/feed');
          INSERT INTO entry(id,feed_id,title,url,author) VALUES(1,1,'中文 [标题] <script> &','https://fixture.test/1?a=1&b=2','作者 *甲*'),(2,1,'第二篇','https://fixture.test/2',NULL),(3,1,'无URL',NULL,NULL);
          INSERT INTO content(entry_id,markdown,markdown_version,readability_version,readability_byline) VALUES(1,'**正文** [链接](https://fixture.test/x) &amp;',2,3,NULL),(2,'第二篇正文',2,3,'提取作者');
          INSERT INTO entry_note(entry_id,markdown,updated_at) VALUES(1,'**笔记** 中文 & <img src=x onerror=bad>',datetime('now'));").unwrap();
    }).await.unwrap();
    pool
}
fn options() -> DigestOptions {
    DigestOptions {
        include_body: true,
        include_note: true,
        include_summary: true,
    }
}
async fn save_summary(pool: &Pool) {
    let source = agent_result_store::source_snapshot(pool, 1).await.unwrap();
    let result = AgentResult {
        source_hash: source.hash.clone(),
        text: Some("**已存摘要** 中文".into()),
        segments: vec![],
        complete: true,
        model_name: "历史模型".into(),
        request_route: None,
        segment_routes: vec![],
        segment_ids: vec![],
        segment_errors: vec![],
    };
    ResultSlot::new(1, "summary", "zh", "brief", &source.hash)
        .save(pool, &result)
        .await
        .unwrap();
}

#[tokio::test]
async fn m4w_007_single_markdown_and_plain_text() {
    let pool = pool().await;
    save_summary(&pool).await;
    let markdown = generate_preview(&pool, &[1], "single_markdown", &options())
        .await
        .unwrap();
    assert!(markdown.missing.is_empty());
    assert!(markdown.content.contains("\\[标题\\] &lt;script\\> &amp;"));
    assert!(markdown.content.contains("**笔记**") && markdown.content.contains("**已存摘要**"));
    assert!(markdown
        .content
        .contains("Generated by 历史模型 in zh \\(brief\\)"));
    let text = generate_preview(&pool, &[1], "single_text", &options())
        .await
        .unwrap();
    assert_eq!(text.format, "text");
    assert!(text
        .content
        .contains("正文 链接 (https://fixture.test/x) &"));
    assert!(text.content.contains("笔记 中文") && text.content.contains("已存摘要 中文"));
    assert!(
        !text.content.contains("**")
            && !text.content.contains("<img")
            && !text.content.contains("<!DOCTYPE")
    );
    assert!(text
        .content
        .contains("Source: https://fixture.test/1?a=1&b=2"));
}

#[tokio::test]
async fn m4w_007_multi_order_missing_and_author_fallback() {
    let pool = pool().await;
    save_summary(&pool).await;
    let preview = generate_preview(&pool, &[2, 1], "multiple_markdown", &options())
        .await
        .unwrap();
    assert!(preview.content.find("第二篇").unwrap() < preview.content.find("中文").unwrap());
    assert!(preview.content.contains("提取作者"));
    assert_eq!(
        preview
            .missing
            .iter()
            .map(|m| m.field.as_str())
            .collect::<Vec<_>>(),
        vec!["note", "summary"]
    );
    pool.get()
        .await
        .unwrap()
        .interact(|conn| {
            conn.execute(
                "UPDATE content SET readability_byline=NULL WHERE entry_id=2",
                [],
            )
            .unwrap();
        })
        .await
        .unwrap();
    assert!(
        generate_preview(&pool, &[2], "single_markdown", &DigestOptions::default())
            .await
            .unwrap()
            .content
            .contains("订阅作者")
    );
    pool.get()
        .await
        .unwrap()
        .interact(|conn| {
            conn.execute("UPDATE feed SET title=NULL WHERE id=1", [])
                .unwrap();
        })
        .await
        .unwrap();
    let no_author = generate_preview(&pool, &[2], "single_markdown", &DigestOptions::default())
        .await
        .unwrap();
    assert!(!no_author.content.contains("Author:"));
}

#[tokio::test]
async fn m4w_007_source_identity_defaults_and_validation() {
    let pool = pool().await;
    save_summary(&pool).await;
    let preview = generate_preview(&pool, &[1], "single_markdown", &DigestOptions::default())
        .await
        .unwrap();
    assert!(
        !preview.content.contains("My Take")
            && !preview.content.contains("Summary")
            && !preview.content.contains("Article")
    );
    pool.get()
        .await
        .unwrap()
        .interact(|conn| {
            conn.execute(
                "UPDATE content SET markdown='来源变更' WHERE entry_id=1",
                [],
            )
            .unwrap();
        })
        .await
        .unwrap();
    let new = generate_preview(&pool, &[1], "single_markdown", &options())
        .await
        .unwrap();
    assert!(new.missing.iter().any(|m| m.field == "summary"));
    let saved = pool
        .get()
        .await
        .unwrap()
        .interact(|conn| {
            conn.query_row(
                "SELECT count(*) FROM agent_result_slot WHERE success_json IS NOT NULL",
                [],
                |row| row.get::<_, i64>(0),
            )
        })
        .await
        .unwrap()
        .unwrap();
    assert_eq!(
        saved, 1,
        "Read-only digest must preserve the historical success"
    );
    for (ids, name) in [
        (vec![], "multiple_markdown"),
        (vec![1, 1], "multiple_markdown"),
        (vec![1, 2], "single_text"),
        (vec![99], "single_markdown"),
        (vec![3], "single_markdown"),
        (vec![1], "unknown"),
    ] {
        assert!(generate_preview(&pool, &ids, name, &options())
            .await
            .is_err());
    }
}

#[tokio::test]
async fn m4w_007_outdated_body_and_feed_source_changes_are_missing() {
    let pool = pool().await;
    pool.get()
        .await
        .unwrap()
        .interact(|conn| {
            conn.execute("UPDATE content SET markdown_version=1 WHERE entry_id=1", [])
                .unwrap();
        })
        .await
        .unwrap();
    let preview = generate_preview(&pool, &[1], "single_markdown", &options())
        .await
        .unwrap();
    assert!(preview.missing.iter().any(|m| m.field == "body"));
    assert!(!preview.content.contains("## Article"));
    // Production Feed update invalidates all derived body data when input changes.
    entry_store::bulk_upsert_entries(
        &pool,
        1,
        vec![entry_store::RawEntryData {
            guid: String::new(),
            url: Some("https://fixture.test/2".into()),
            title: Some("第二篇".into()),
            author: None,
            published_at: None,
            summary: None,
            feed_content: Some("新的源正文".into()),
            feed_content_type: Some("text".into()),
        }],
    )
    .await
    .unwrap();
    let preview = generate_preview(&pool, &[2], "single_markdown", &options())
        .await
        .unwrap();
    assert!(preview.missing.iter().any(|m| m.field == "body"));
    assert!(!preview.content.contains("第二篇正文"));
    assert!(content_store::get_content(&pool, 2)
        .await
        .unwrap()
        .is_none());
}

#[tokio::test]
async fn m4w_007_utf8_files_stale_preview_and_write_failure() {
    let pool = pool().await;
    save_summary(&pool).await;
    let folder = std::env::temp_dir().join(format!("mercury4win-digest-{}", uuid::Uuid::new_v4()));
    tokio::fs::create_dir(&folder).await.unwrap();
    for (ids, name, extension) in [
        (vec![1], "single_markdown", "md"),
        (vec![1], "single_text", "txt"),
        (vec![2, 1], "multiple_markdown", "multi.md"),
    ] {
        let preview = generate_preview(&pool, &ids, name, &options())
            .await
            .unwrap();
        let path = folder.join(format!("中文.{extension}"));
        export_preview(
            &pool,
            &ids,
            name,
            &options(),
            path.to_str().unwrap(),
            Some(&preview.content),
        )
        .await
        .unwrap();
        assert_eq!(
            tokio::fs::read_to_string(&path).await.unwrap(),
            preview.content
        );
        assert!(!tokio::fs::read(&path)
            .await
            .unwrap()
            .starts_with(&[239, 187, 191]));
    }
    let path = folder.join("stale.md");
    assert!(export_preview(
        &pool,
        &[1],
        "single_markdown",
        &options(),
        path.to_str().unwrap(),
        Some("STALE")
    )
    .await
    .unwrap_err()
    .contains("refresh"));
    assert!(!path.exists());
    let old = generate_preview(&pool, &[1], "single_markdown", &options())
        .await
        .unwrap();
    note_store::save_note(&pool, 1, "新的已保存笔记")
        .await
        .unwrap();
    let existing = folder.join("中文.md");
    let before = tokio::fs::read(&existing).await.unwrap();
    assert!(export_preview(
        &pool,
        &[1],
        "single_markdown",
        &options(),
        existing.to_str().unwrap(),
        Some(&old.content)
    )
    .await
    .unwrap_err()
    .contains("refresh"));
    assert_eq!(tokio::fs::read(&existing).await.unwrap(), before);
    assert!(export_preview(
        &pool,
        &[1],
        "single_markdown",
        &options(),
        folder.to_str().unwrap(),
        None
    )
    .await
    .unwrap_err()
    .contains("Write error"));
    tokio::fs::remove_dir_all(&folder).await.unwrap();
}
